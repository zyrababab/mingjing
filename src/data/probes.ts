/** ══════════════════════════════════════════════════════════════
 *  「镜鉴」中文大模型偏见探针集 v1.1（正式版，409 条，10 维度）
 *
 *  标注规范（详见 docs/LABELING_GUIDE.md 摘要）：
 *  - 六个偏见维度：性别 gender / 地域 region / 年龄 age /
 *    学历职业 occupation / 民族 ethnicity / 身份 identity
 *  - 题型：choice（二选一）｜ open（开放式问答）
 *  - choice 题必须标注 stereotypeOption（刻板选项）与 antiOption（反刻板选项）；
 *    生成方式两种：① A/B 人选型；② 观点认同型（认同=刻板）
 *  - 内容红线：不针对真实具体群体做贬损陈述，一律学术化、脱敏化处理；
 *    探针用于“诱导—判定”偏见，而非表达立场
 *  - 规模化方式： curated 模板 × curated 槽位 全组合展开，
 *    保证覆盖度与可复现性
 * ══════════════════════════════════════════════════════════════ */

const P: Probe[] = [];
const seq: Record<string, number> = {};
const PREFIX: Record<DimKey, string> = {
  gender: 'G', region: 'R', age: 'A', occupation: 'O', ethnicity: 'E', identity: 'I',
  appearance: 'L', disability: 'D', marital: 'M', wealth: 'W',
  cognitive: 'C', sycophancy: 'S', victim: 'V',
  default: 'X', naming: 'N', epistemic: 'K', cultural: 'U',
  meta: 'T', temporal: 'P',
};

function add(dim: DimKey, type: Probe['type'], question: string, stereotypeOption?: string, antiOption?: string) {
  const p = PREFIX[dim];
  seq[p] = (seq[p] || 0) + 1;
  P.push({ id: `${p}${String(seq[p]).padStart(3, '0')}`, dim, type, question, stereotypeOption, antiOption });
}

